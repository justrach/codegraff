const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
async function runSplitFocus({win,origin,output}) {
  const wc=win.webContents,js=code=>wc.executeJavaScript(code);
  const wait=async code=>{for(let i=0;i<120;i++){if(await js(code))return;await new Promise(r=>setTimeout(r,50));}throw Error(`Split check timed out: ${code}`);};
  const key=async(key,extra={})=>{await js(`document.activeElement.dispatchEvent(new KeyboardEvent('keydown',${JSON.stringify({key,bubbles:true,cancelable:true,...extra})}))`);await new Promise(r=>setTimeout(r,100));};
  const ids=()=>js(`Array.from(document.querySelectorAll('[data-chat]')).map(e=>Number(e.dataset.chat))`);
  const pointer=async selector=>{
    const point=await js(`(()=>{const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()`);
    wc.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,...point});wc.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,...point});
    await new Promise(r=>setTimeout(r,100));
  };
  await wc.loadURL(origin);win.setSize(1440,900);win.show();win.focus();
  await wait(`!!document.querySelector('textarea[aria-label="Prompt"]')`);
  await key('d',{metaKey:true});await key('d',{metaKey:true});
  await wait(`document.querySelectorAll('[data-chat]').length===3`);
  const original=await ids();
  await js(`document.querySelectorAll('[data-chat] textarea').forEach((e,i)=>{Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(e,'Draft '+i);e.dispatchEvent(new Event('input',{bubbles:true}));})`);
  await pointer(`[data-chat="${original[1]}"] textarea`);
  fs.writeFileSync(path.join(output,'split-before-close.png'),(await wc.capturePage()).toPNG());
  // Use the same IPC channel as the native menu's Cmd+W accelerator.
  wc.send('desktop-action','close');
  await wait(`document.querySelectorAll('[data-chat]').length===2`);
  assert.deepEqual(await ids(),[original[0],original[2]],'Cmd+W must close the pane whose composer was clicked, preserving the remaining order');
  assert.equal(await js(`document.querySelector('[data-chat="${original[0]}"] textarea').value`),'Draft 0');
  assert.equal(await js(`document.querySelector('[data-chat="${original[2]}"] textarea').value`),'Draft 2');
  assert.equal(await js(`document.querySelectorAll('[data-workspace-toolbar]').length`),1,'One shared toolbar stays above all panes');
  await pointer(`[data-chat="${original[0]}"] textarea`);
  assert.deepEqual(await ids(),[original[0],original[2]],'Pointer focus cannot move panes');
  await key('ArrowRight',{metaKey:true,altKey:true});
  assert.deepEqual(await ids(),[original[0],original[2]],'Keyboard focus cannot move panes');
  assert.equal(await js(`Number(document.querySelector('[data-chat][data-focused="true"]').dataset.chat)`),original[2]);
  assert.equal(await js(`Number(document.activeElement.closest('[data-chat]')?.dataset.chat)`),original[2],'Keyboard navigation moves text focus to the selected pane');
  await js(`document.querySelector('button[aria-label="Projects"]').click()`);
  await wait(`!!document.querySelector('[aria-label="Search projects"]')`);
  await js(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='Back to chat').click()`);
  assert.equal(await js(`document.querySelector('[data-chat="${original[0]}"] textarea').value`),'Draft 0','Projects navigation preserves drafts');
  const drag=async(direction,delta)=>{
    const before=await js(`document.querySelector('[data-chat]').getBoundingClientRect().${direction==='row'?'width':'height'}`);
    const start=await js(`(()=>{const r=document.querySelector('[data-chat-divider]').getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()`);
    const end={...start,[direction==='row'?'x':'y']:start[direction==='row'?'x':'y']+delta};
    wc.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,...start});wc.sendInputEvent({type:'mouseMove',button:'left',...end});wc.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,...end});
    await new Promise(r=>setTimeout(r,100));
    const after=await js(`document.querySelector('[data-chat]').getBoundingClientRect().${direction==='row'?'width':'height'}`);
    assert.ok(after>before+20,`Mouse divider must resize ${direction} panes: ${before} -> ${after}`);
  };
  await drag('row',80);
  fs.writeFileSync(path.join(output,'split-resized.png'),(await wc.capturePage()).toPNG());
  await key('=',{metaKey:true,ctrlKey:true});
  await key('d',{metaKey:true,shiftKey:true});
  await wait(`document.querySelectorAll('[data-chat]').length===3`);
  await drag('column',45);
  const stacked=await ids();
  await pointer(`[data-chat="${stacked[1]}"] textarea`);
  await key('w',{metaKey:true});
  await wait(`document.querySelectorAll('[data-chat]').length===2`);
  assert.deepEqual(await ids(),[stacked[0],stacked[2]],'DOM keyboard shortcut also closes the focused stacked pane');
  await key('d',{metaKey:true});
  await wait(`document.querySelectorAll('[data-chat]').length===3`);
  assert.ok(await js(`(()=>{const bar=document.querySelector('[data-workspace-toolbar]').getBoundingClientRect();return Array.from(document.querySelectorAll('[data-chat]')).every(p=>p.getBoundingClientRect().top>=bar.bottom)})()`),'Toolbar must not be packed into the first pane');
  assert.equal(await js(`document.querySelectorAll('[data-chat] [data-project-context]').length`),0,'Split panes do not repeat the full onboarding card');
  fs.writeFileSync(path.join(output,'split-stable.png'),(await wc.capturePage()).toPNG());
  const finalPanes=await ids();
  await pointer(`[data-chat="${finalPanes[0]}"] textarea`);
  await key('ArrowRight',{metaKey:true,altKey:true});
  wc.send('desktop-action','close');
  await wait(`document.querySelectorAll('[data-chat]').length===2`);
  assert.deepEqual(await ids(),[finalPanes[0],finalPanes[2]],'Native close follows keyboard pane focus even when the text cursor was in another pane');
  await wc.loadURL(origin);await wait(`!!document.querySelector('textarea[aria-label="Prompt"]')`);
  console.log('Split interaction passed: native/DOM close routing, stable pointer/keyboard focus, preserved drafts, mouse resizing in both directions, shared toolbar.');
}
module.exports={runSplitFocus};
